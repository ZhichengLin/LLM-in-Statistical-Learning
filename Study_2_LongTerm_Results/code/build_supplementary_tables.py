#!/usr/bin/env python3
"""Generate Supplementary Tables S22-S24 for the no-tools long-term reanalysis from aggregate results only.

Primary sample: the 33 eligible participants (no reported external tool/material use) who completed both follow-ups;
focal sensitivity: all 39 eligible long-term returners. Inputs: OUT/results/*.csv (this run). No participant data.
Output: OUT/tables/Supplementary_Tables_S22-S24_no_tools.md
Formatting: accuracy in % or percentage points (pp, 1 decimal); confidence in scale points (2 decimals, 3 for interval
limits within 0.01 of zero); P < 0.001 or 3 decimals; minus sign U+2212.
Usage: build_supplementary_tables.py --out DIR
"""
import argparse
import csv
import sys
from pathlib import Path

MINUS = '−'
LABEL = {'AI': 'AI', 'AI Human': 'AI + Human', 'Human': 'Human'}


def rd(path):
    return list(csv.DictReader(open(path, newline='', encoding='utf-8')))


def num(x, d=1, scale=1.0):
    v = float(x) * scale
    s = f'{v:.{d}f}'
    if float(s) == 0:
        return f'{0:.{d}f}'
    return MINUS + s[1:] if s.startswith('-') else s


def ci(lo, hi, d=1, scale=1.0):
    def f(v):
        v = float(v) * scale
        return num(v, 3 if (scale == 1.0 and d == 2 and abs(v) < 0.01) else d)
    return f'[{f(lo)}, {f(hi)}]'


def pval(p):
    p = float(p)
    return '< 0.001' if p < 0.001 else f'{p:.3f}'


def contrast_name(c):
    return c.replace('LT-', 'LT − ').replace('M1', 'one month')


def label_pair(c):
    c = c.replace('(AI Human)', 'AI Human')
    a, b = [x.strip() for x in c.split(' - ')]
    return f'{LABEL[a]} − {LABEL[b]}'


def md_table(header, rows):
    out = ['| ' + ' | '.join(header) + ' |', '| ' + ' | '.join('---' for _ in header) + ' |']
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    out = Path(a.out).resolve()
    R = lambda f: rd(out / 'results' / f)
    flow = {r['quantity']: r for r in R('sample_flow.csv')}
    frac = {r['quantity']: float(r['total']) for r in R('sample_flow.csv') if '/' in r['quantity']}
    sel = {(r['group'], r['variable']): r for r in R('selection_descriptives.csv')}
    ax = {(r['sample'], r['measure'], r['category']): r['n'] for r in R('auxiliary_counts.csv')}
    pc = R('paired_contrasts.csv')
    lbt = R('label_balanced_temporal.csv')
    lc = R('label_contrasts.csv')
    om = R('mlm33_omnibus.csv')[0]
    tm = {r['sample']: r for r in R('correction_timing.csv')}
    gd = {r['model']: r for r in R('gls_diagnostics.csv')}
    gx = {r['check']: r for r in R('gls_crosscheck.csv')}
    fgc = R('fullcohort_gls_contrasts.csv')
    flc = R('fullcohort_lmer_contrasts.csv')
    fgl = R('fullcohort_gls_lt_labels.csv')
    fdg = R('fullcohort_diagnostics.csv')
    fvc = R('fullcohort_lmer_variance_components.csv')
    ab = R('attrition_bounds.csv')[0]
    order = R('item_order_association.csv')[0]
    ss = R('df_seed_sensitivity.csv')
    diag = {(r['model'], r['measure']): r for r in fdg}
    L = []
    L.append('# Supplementary Tables S22–S24 (no-tools eligibility; primary 33, sensitivity 39)\n')
    L.append('Generated by `code/build_supplementary_tables.py` from aggregate outputs of the frozen 44-submission snapshot. All '
             'long-term analyses are exploratory and were not preregistered. Two reporting decisions were made after long-term '
             'results were known: participants with both follow-ups form the primary sample, and self-reported use of external '
             'tools or materials (AI tools, websites, books or notes) while answering the long-term items is a mandatory '
             'eligibility exclusion (5 of 44 submissions; a self-report, not proof of unaided answering). Excluded participants’ '
             'records are omitted from every long-term analysis, including the full-cohort models (cohort of 170). The original '
             'initial-session (n = 175) and one-month (n = 84) results are unchanged historical results. Accuracy is the '
             'equal-weighted mean of the three task proportions (percentage points, pp).\n')

    # ---------------- Table S22 ----------------
    L.append('## Table S22. Long-term follow-up sample, eligibility, selection, and attrition\n')
    L.append('### A. Coverage by original source label\n')
    rows = []
    for key, name in [('AI', 'AI'), ('AI_Human', 'AI + Human'), ('Human', 'Human'), ('total', 'Total')]:
        rows.append([name] + [flow[q][key] for q in ['cohort175', 'one_month_completers_original', 'longterm_returns',
                                                    'excluded_reported_tool_use', 'eligible39', 'primary33']])
    L.append(md_table(['Label', 'Analytic cohort', 'One-month completers', 'Long-term submissions', 'Excluded: reported tool/material use',
                       'Eligible long-term', 'Eligible with both follow-ups (primary)'], rows) + '\n')
    L.append('Observation counts (submissions) are distinguished from eligibility counts. No response to the tool-use question was '
             'missing or unknown; any such response would also have been ineligible.\n')
    L.append('### B. Participant flow and coverage\n')
    rows = [['Long-term submissions matched to the analytic cohort', flow['longterm_returns']['total'], f"{flow['longterm_returns']['total']} of 175"],
            ['Excluded: reported external tool/material use', flow['excluded_reported_tool_use']['total'], 'all Human label; all had one-month data'],
            ['Eligible long-term returners (sensitivity)', flow['eligible39']['total'], f"{100 * frac['39/170']:.1f}% of the 170-person long-term cohort"],
            ['Eligible with both follow-ups (primary)', flow['primary33']['total'],
             f"{100 * frac['33/170']:.1f}% of 170; {100 * frac['33/79']:.1f}% of the 79 eligible one-month completers"],
            ['Eligible without one-month data', flow['additional6']['total'], f"{100 * frac['6/91']:.1f}% of the 91 without one-month data; descriptive only"],
            ['One-month only', flow['one_month_only']['total'], ''],
            ['Neither follow-up', flow['neither_followup']['total'], '']]
    L.append(md_table(['Pattern', 'n', 'Coverage / note'], rows) + '\n')
    L.append('### C. Selection profile: mean (SD) equal-task accuracy, %\n')
    rows = []
    for g, name in [('primary33', 'Primary 33'), ('additional6', 'Eligible, long-term only (6)'), ('one_month_only', 'One-month only (46)'),
                    ('neither_followup', 'Neither follow-up (85)')]:
        row = [name]
        for v in ['S1_accuracy', 'S2_accuracy', 'S3_accuracy', 'M1_accuracy', 'LT_accuracy']:
            r = sel.get((g, v))
            row.append('—' if r is None else f"{num(r['mean'], 1, 100)} ({num(r['sd'], 1, 100)})")
        rows.append(row)
    L.append(md_table(['Group (within the 170-person cohort)', 'S1', 'S2', 'S3', 'One month', '14 months'], rows) + '\n')
    L.append('Groups are defined by follow-up participation, which was not randomized; differences describe selection and are not tested. '
             'The five excluded participants are not summarized.\n')
    L.append('### D. Recorded long-term auxiliary measures (eligible participants)\n')
    rows = []
    for m, cats in [('source recall', ['correct', 'incorrect', 'do not remember']), ('prior similar-item exposure', ['yes', 'unsure', 'no']),
                    ('recorded item-order condition', ['fixed', 'randomized'])]:
        for c in cats:
            rows.append([m, c, ax[('primary33', m, c)], ax[('eligible39', m, c)]])
    rows.append(['external-tool/material use', 'no (eligibility)', ax[('primary33', 'external-tool use (eligibility)', 'no')],
                 ax[('eligible39', 'external-tool use (eligibility)', 'no')]])
    for c in ['mean', 'sd', 'min', 'max']:
        rows.append(['interval (days)', c.upper() if c == 'sd' else c, f"{float(ax[('primary33', 'interval days', c)]):.1f}",
                     f"{float(ax[('eligible39', 'interval days', c)]):.1f}"])
    L.append(md_table(['Measure', 'Category', 'Primary 33', 'Eligible 39'], rows) + '\n')
    L.append('Source recall has no exclusion role. Prior exposure defines an ancillary robustness subset within eligible participants.\n')
    L.append('### E. Missing-outcome sensitivity for the 170-person cohort\n')
    L.append(f"If each of the {ab['missing']} missing 14-month outcomes could lie anywhere from 0 to 1, the cohort mean baseline-to-14-month "
             f"change is only partially identified, within [{num(ab['lower_change'], 1, 100)}, {num(ab['upper_change'], 1, 100)}] pp "
             f"(identification bounds, not confidence intervals). A zero cohort change would require nonreturners to average "
             f"{num(ab['missing_LT_mean_for_zero_change'], 1, 100)}% at 14 months, versus their observed baseline mean of "
             f"{num(ab['nonreturner_S1_mean'], 1, 100)}%. Neither MAR nor this scenario is verifiable. The cohort excludes the five tool users entirely.\n")

    # ---------------- Table S23 ----------------
    L.append('## Table S23. Long-term accuracy\n')
    hdr = ['Contrast', 'n', 'Reference mean, %', '14-month mean, %', 'Difference, pp', 'SE', '95% t CI', 'Bootstrap 95% CI', 't (df)', 'P', 'Holm P']

    def paired_rows(sample, measure='accuracy', weighting='equal-task'):
        rows_ = []
        conf = measure == 'confidence'
        for r in [x for x in pc if x['sample'] == sample and x['measure'] == measure and x['weighting'] == weighting]:
            sc, d = (1.0, 2) if conf else (100.0, 1)
            rows_.append([contrast_name(r['contrast']), r['n'], num(r['reference_mean'], d, sc), num(r['longterm_mean'], d, sc),
                          num(r['estimate'], d, sc), num(r['SE'], 3 if conf else 2, sc), ci(r['lower'], r['upper'], d, sc),
                          ci(r['boot_lower'], r['boot_upper'], d, sc), f"{num(r['t'], 2)} ({int(float(r['df']))})", pval(r['p']), pval(r['p_holm'])])
        return rows_

    L.append('### A. Primary: observed paired changes among the 33 eligible participants who completed both follow-ups\n')
    L.append(md_table(hdr, paired_rows('primary33')) + '\n')
    L.append('Holm adjustment within the three contrasts; t intervals are pointwise; percentile bootstrap intervals use 5,000 participant '
             'resamples (seed 20260930). These rows equal the earlier package’s “primary 38 without reported tool use” rows, '
             'including the bootstrap intervals, because the participants and random-number sequence are the same.\n')
    L.append('### B. Focal sensitivity: all 39 eligible long-term returners (one-month participation not required)\n')
    L.append(md_table(hdr, paired_rows('eligible39')) + '\n')
    L.append('The LT − one month contrast uses the same 33 participant pairs as Panel A (the six added participants have no one-month data), '
             'so its estimate, t interval and P are identical; only the bootstrap draws differ (different position in the random-number '
             'sequence). It is not an independent replication.\n')
    L.append('### C. Ancillary robustness within eligible participants\n')
    rows = []
    for sample, weighting, name in [('primary33_no_prior_exposure', 'equal-task', 'Primary 33, no reported/unsure prior exposure'),
                                    ('eligible39_no_prior_exposure', 'equal-task', 'Eligible 39, no reported/unsure prior exposure'),
                                    ('primary33_item_weighted', '17-item', 'Primary 33, 17-item weighting'),
                                    ('eligible39_item_weighted', '17-item', 'Eligible 39, 17-item weighting')]:
        for r in [x for x in pc if x['sample'] == sample and x['measure'] == 'accuracy' and x['weighting'] == weighting]:
            rows.append([name, contrast_name(r['contrast']), r['n'], num(r['estimate'], 1, 100), ci(r['lower'], r['upper'], 1, 100),
                         ci(r['boot_lower'], r['boot_upper'], 1, 100), pval(r['p_holm'])])
    L.append(md_table(['Sample', 'Contrast', 'n', 'Difference, pp', '95% t CI', 'Bootstrap 95% CI', 'Holm P'], rows) + '\n')
    L.append('Each sample × weighting forms its own Holm family of three. LT − one month rows of the 39-based families use the same '
             'participants as the corresponding 33-based rows.\n')
    L.append('### D. Model-based estimands (labels weighted equally)\n')
    rows = []
    for r in lbt:
        name = 'Exact multivariate linear model, primary 33' if r['population'] == 'primary33' else 'Unstructured GLS, eligible 39'
        md = 'complete data' if r['population'] == 'primary33' else 'MAR for one-month data of 6 participants'
        df = f"{float(r['df']):.0f}" if r['df_method'] == 'exact residual' else f"{float(r['df']):.1f} (approx.†)"
        rows.append([name, md, contrast_name(r['contrast']), num(r['estimate'], 1, 100), ci(r['lower'], r['upper'], 1, 100), df, pval(r['p_holm'])])
    for r in [x for x in fgc if x['model'].startswith('accuracy')]:
        dg = diag[(r['model'], 'accuracy')]
        if r['model'] == 'accuracy_unadjusted':
            name, dfs = 'Unstructured GLS, cohort 170', f"{float(r['df']):.0f} (residual‡)"
        else:
            name, dfs = f"Unstructured GLS, covariate-adjusted, {dg['participants']} of 170", f"{float(r['df']):.1f} (approx.†)"
        rows.append([name, f"MAR, {int(dg['participants']) - 39} 14-month outcomes missing", contrast_name(r['contrast']), num(r['estimate'], 1, 100),
                     ci(r['lower.CL'], r['upper.CL'], 1, 100), dfs, pval(r['p_holm'])])
    nm = {'historical_structure': 'Participant-intercept continuation, 170', 'task_dependence': 'Task-structured continuation, 170',
          'task_adjusted': 'Task-structured continuation, covariate-adjusted, 168'}
    for r in [x for x in flc if x['measure'] == 'accuracy']:
        rows.append([nm[r['model']], 'MAR (task rows)', contrast_name(r['contrast']), num(r['estimate'], 1, 100), ci(r['lower.CL'], r['upper.CL'], 1, 100),
                     f"{float(r['df']):.1f} (KR)", pval(r['p_holm'])])
    L.append(md_table(['Analysis', 'Missing data', 'Contrast', 'Difference, pp', '95% CI', 'df', 'Holm P'], rows) + '\n')
    un = diag[('accuracy_unadjusted', 'accuracy')]
    L.append('Paired estimates (Panels A–C) weight participants equally; model-based estimates weight labels equally. The cohort models '
             'target a different population (the analytic cohort minus the five excluded participants) under a missing-at-random (MAR) '
             'assumption and are not corrections of the paired estimates. '
             f"†Approximate Satterthwaite df (emmeans appx-satterthwaite) depend on the random-number state; Table S24C reports their spread. "
             f"‡Satterthwaite df were requested but unavailable: the approximate covariance of the variance parameters was "
             f"“{un['apVar_message']}”, so emmeans used the residual df ({float(un['df_error_used']):.0f}); intervals and P for this model "
             'are therefore closer to normal-theory values than intended.\n')
    gm = {(r['model'], r['Phase']): r for r in R('gls_means.csv') if r['Label'] == 'equal-weighted'}
    fm = {r['Phase']: r for r in R('fullcohort_gls_means.csv') if r['model'] == 'accuracy_unadjusted'}
    rows = []
    for name, miss, get in [('Primary 33, complete data (exact model = GLS estimates)', '0 / 0', lambda ph: gm[('gls33', ph)]['emmean']),
                            ('Eligible 39, unstructured GLS', '6 / 0', lambda ph: gm[('gls39', ph)]['emmean']),
                            ('Cohort 170, unstructured GLS', '91 / 131', lambda ph: fm[{'S1': 'stage1', 'M1': 'follow', 'LT': 'follow2'}[ph]]['emmean'])]:
        s1, m1, lt = (float(get(ph)) for ph in ['S1', 'M1', 'LT'])
        rows.append([name, miss, num(s1, 1, 100), num(m1, 1, 100), num(lt, 1, 100), num(lt - m1, 1, 100)])
    L.append('Model-based wave means (equal label weights):\n')
    L.append(md_table(['Approach', 'Missing outcomes (one month / 14 months)', 'S1, %', 'One month, %', '14 months, %', '14 months − one month, pp'], rows) + '\n')
    L.append('The cohort means include MAR model predictions for participants without one-month (91) or 14-month (131) data. These data cannot establish which missing-data assumption holds.\n')
    L.append('### E. Source-label comparisons at 14 months\n')
    L.append(f"Omnibus Phase × Label test in the primary 33 (multivariate test of the four within-person changes from S1): Pillai’s trace = "
             f"{float(om['value']):.3f}, approximate F({int(float(om['df1']))}, {int(float(om['df2']))}) = {float(om['approx_F']):.2f}, P = {pval(om['p'])}. "
             'This single omnibus, specified in the retrospective analysis contract before model fitting, includes initial-session label '
             'differences; a nonsignificant result does not establish parallel trajectories.\n')
    rows = []
    for r in lc:
        pop = 'Primary 33' if r['population'] == 'primary33' else 'Eligible 39'
        fam = '14-month level' if r['family'] == 'LT level' else 'LT − S1 gain'
        rows.append([pop, fam, label_pair(r['contrast']), num(r['estimate'], 1, 100), ci(r['lower'], r['upper'], 1, 100), f"{int(float(r['df']))}", pval(r['p_adjusted'])])
    for r in [x for x in fgl if x['model'] == 'accuracy_unadjusted']:
        rows.append(['Cohort 170, unstructured GLS', '14-month level', label_pair(r['contrast']), num(r['estimate'], 1, 100),
                     ci(r['lower.CL'], r['upper.CL'], 1, 100), f"{float(r['df']):.0f} (residual‡)", pval(r['p.value'])])
    L.append(md_table(['Sample / model', 'Family', 'Comparison', 'Difference, pp', 'Tukey 95% CI', 'df', 'Tukey P'], rows) + '\n')
    L.append('Each sample × family is a Tukey family of three. The 33 and 39 comparisons use per-person scores with exact residual df. '
             'Nonsignificant comparisons do not establish equivalence. After the exclusion, the Human group has 7 (primary) or 8 (eligible) '
             'participants, so label comparisons involving Human are especially imprecise.\n')

    # ---------------- Table S24 ----------------
    L.append('## Table S24. Secondary long-term analyses\n')
    L.append('### A. Recorded confidence (exploratory)\n')
    L.append('Confidence is the recorded 1–5 rating. The deployed long-term program’s labels, their order and the ascending 1–5 codes match the '
             'original instrument; the historical platform delivery of the earlier waves was not independently audited.\n')
    rows = []
    for sample, name in [('primary33', 'Primary 33'), ('eligible39', 'Eligible 39'), ('primary33_no_prior_exposure', 'Primary 33, no prior exposure'),
                         ('eligible39_no_prior_exposure', 'Eligible 39, no prior exposure')]:
        for r in [x for x in pc if x['sample'] == sample and x['measure'] == 'confidence']:
            rows.append([name, contrast_name(r['contrast']), r['n'], num(r['estimate'], 2), ci(r['lower'], r['upper'], 2),
                         ci(r['boot_lower'], r['boot_upper'], 2), pval(r['p_holm'])])
    L.append(md_table(['Sample', 'Contrast', 'n', 'Difference, scale points', '95% t CI', 'Bootstrap 95% CI', 'Holm P'], rows) + '\n')
    m1c = next(x for x in pc if x['sample'] == 'primary33' and x['measure'] == 'confidence' and x['contrast'] == 'LT-M1')
    L.append('The t and bootstrap 95% CIs are pointwise (unadjusted); P values are Holm-adjusted within each three-contrast family '
             '(bootstrap B = 5,000, seed 20260930). A pointwise interval can therefore exclude zero while the Holm-adjusted P exceeds 0.05: '
             f"in the primary 33, the 14-month minus one-month confidence difference was {num(m1c['estimate'], 2)} points "
             f"(pointwise 95% t CI {ci(m1c['lower'], m1c['upper'], 2)}; unadjusted P = {pval(m1c['p'])}; Holm-adjusted P = {pval(m1c['p_holm'])}).\n")
    L.append('### B. Correction timing (exploratory common odds ratio)\n')
    rows = []
    for s, name in [('primary33', 'Primary 33'), ('eligible39', 'Eligible 39')]:
        r = tm[s]
        rows.append([name, r['participants'], r['responses'], f"{r['early_responses']} / {r['late_responses']}",
                     f"{num(r['observed_LT_early'], 1, 100)} / {num(r['observed_LT_late'], 1, 100)}", f"{float(r['or']):.2f}",
                     f"[{float(r['profile_lower']):.2f}, {float(r['profile_upper']):.2f}]", pval(r['p_wald'])])
    L.append(md_table(['Sample', 'Participants', 'Eligible responses', 'Early / late responses', 'Observed 14-month correct, early / late, %',
                       'Common OR (early vs late)', 'Profile 95% CI', 'Wald P'], rows) + '\n')
    L.append('Eligibility: incorrect at S1 and correct at S2 or S3; items correct at S2 count as early even if incorrect at S3. Binomial-logit '
             'mixed model with timing (late reference), label, task, centered item difficulty and baseline accuracy, with participant and item '
             'intercepts (item intercept retained; no convergence, singularity, separation or profile warnings). Item difficulty is the fixed '
             'original-study per-item mean S1 correctness over the 175 initial-session participants; no excluded participant contributes a '
             'response row. Timing is posttreatment and not randomized; the OR is not compared with the one-month interaction-model OR.\n')
    L.append('### C. Model diagnostics\n')
    rows = []
    for m, name in [('gls33', 'GLS, primary 33 (equivalence diagnostic)'), ('gls39', 'GLS, eligible 39')]:
        r = gd[m]
        rows.append([name, r['rows'], r['participants'], r['covariance'], r['df_mode'], f"{float(r['min_eigen_cov']):.4f}"])
    L.append(md_table(['Model', 'Participant-wave rows', 'Participants', 'Covariance', 'df method', 'Minimum eigenvalue of covariance'], rows) + '\n')
    g33 = gx['GLS33 vs exact MLM33']
    lo, hi = (float(x) for x in g33['gls_df_range'].split('-'))
    L.append(f"In the complete 33, GLS reproduced the exact multivariate-linear-model estimates (maximum difference {float(g33['max_abs_d_estimate']):.0e}) "
             f"and standard errors (maximum relative difference {float(g33['max_rel_d_se']):.0e}); its approximate df ranged {lo:.1f}–{hi:.1f} versus the "
             'exact 30, so exact t(30) inference is reported for the 33.\n')
    rows = []
    for r in fdg:
        vc = [x for x in fvc if x['model'] == r['model'] and x['measure'] == r['measure']]
        comp = '; '.join(f"{x['component']} {float(x['variance']):.4f}" for x in vc) if vc else ''
        rows.append([r['model'].replace('_', ' '), r['measure'], r['participants'], r['nobs'], r['covariance'],
                     f"{r['requested_df_mode']} → {r['effective_df_mode']}", r['apVar_available'] or '—',
                     {'TRUE': 'yes', 'FALSE': 'no'}.get(r['singular'], '—'), comp or '—'])
    L.append('Cohort (170) model diagnostics:\n')
    L.append(md_table(['Model', 'Outcome', 'Participants', 'Rows', 'Covariance', 'df requested → used', 'apVar available', 'Singular',
                       'Variance components (lmer)'], rows) + '\n')
    sing = [r for r in fdg if r['singular'] == 'TRUE']
    L.append(('The covariate-adjusted task-structured confidence model is singular: its participant-by-task variance is estimated at the boundary (0), '
              'the same pattern as the historical 173-person fit. Its estimates are reported unchanged (no specification change was made) and are '
              'not used in any proposed manuscript statement. ' if sing else '') +
             f"The unadjusted cohort GLS could not provide Satterthwaite df (“{un['apVar_message']}”); residual df were used.\n")
    by = {}
    for r in ss:
        by.setdefault((r['model'], r['contrast']), []).append(r)
    rows = []
    for (m, c), v in by.items():
        dfs = [float(x['df']) for x in v]; ps = [float(x['p']) for x in v]
        lows = [float(x['lower']) for x in v]; ups = [float(x['upper']) for x in v]
        scale = 100.0 if 'confidence' not in m else 1.0
        d = 1 if scale == 100.0 else 2
        rows.append([m, contrast_name(c), f"{min(dfs):.1f}–{max(dfs):.1f}", f"{pval(min(ps))}–{pval(max(ps))}",
                     f"{num(min(lows), d, scale)} to {num(max(lows), d, scale)}", f"{num(min(ups), d, scale)} to {num(max(ups), d, scale)}"])
    L.append('Numerical diagnostic: sensitivity of approximate Satterthwaite df to the random-number state (pipeline value and two further '
             'fixed seeds; estimates and SEs verified equal across seeds; P values unadjusted):\n')
    L.append(md_table(['Model', 'Contrast', 'df range', 'Unadjusted P range', 'Lower CI bound range', 'Upper CI bound range'], rows) + '\n')
    L.append('### D. Recorded item-order association (eligible 39)\n')
    L.append(f"Randomized − fixed recorded order, adjusted for original label and baseline accuracy (HC3): {num(order['estimate'], 1, 100)} pp, "
             f"95% CI {ci(order['lower'], order['upper'], 1, 100)}, P = {pval(order['p'])} (n = {order['n']}; {order['fixed']} fixed, {order['randomized']} randomized). "
             'Order was directly randomized according to the student and the deployed programs differ only in the condition constant; the historical '
             'allocation record is unaudited, so this is reported as an association.\n')
